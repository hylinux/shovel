const placeholders = /\{p\d+\}/g;
const patterns = Object.entries(chinese).filter(([message]) => /\{p\d+\}/.test(message)).map(([message, translated]) => {
  const names = message.match(placeholders) || [];
  const parts = message.split(placeholders).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  return { message, expression: new RegExp(`^${parts.join("([\\s\\S]*?)")}$`), names, translated };
});

export function isLocale(value: string | null): value is Locale {
  return value === "en" || value === "zh-CN";
}

export function readLocale(storage: Pick<Storage, "getItem">): Locale {
  const saved = storage.getItem(localeStorageKey);
  return isLocale(saved) ? saved : defaultLocale;
}

export function writeLocale(storage: Pick<Storage, "setItem">, locale: Locale): void {
  storage.setItem(localeStorageKey, locale);
}

function interpolate(message: string, values: TranslationValues): string {
  return message.replace(placeholders, token => {
    const name = token.slice(1, -1);
    return Object.hasOwn(values, name) ? String(values[name] ?? "") : token;
  });
}

export function translate(message: string, locale: Locale, values: TranslationValues = {}): string {
  if (locale === "en") return interpolate(message, values);
  const normalized = message.replace(/\s+/g, " ").trim();
  const key = Object.hasOwn(chinese, normalized) ? normalized : normalized.replaceAll("_", " ");
  const translated = Object.hasOwn(chinese, key) ? chinese[key] : undefined;
  if (translated !== undefined) {
    const prefix = message.match(/^\s*/)?.[0] || "";
    const suffix = message.match(/\s*$/)?.[0] || "";
    return prefix + interpolate(translated, values) + suffix;
  }
  for (const pattern of patterns) {
    const match = pattern.expression.exec(normalized);
    if (match) {
      const captured = Object.fromEntries(pattern.names.map((name, index) => [name.slice(1, -1), match[index + 1]]));
      if (pattern.message.startsWith("Recovered ")) captured.p1 = translate(captured.p1, locale);
      if (pattern.message === "{p0} queued. Follow it in Background tasks.") captured.p0 = translate(captured.p0, locale);
      return interpolate(pattern.translated, captured);
    }
  }
  const recoveryHint = " Check session history before resending.";
  if (message.endsWith(recoveryHint)) {
    return `${translate(message.slice(0, -recoveryHint.length), locale)} ${chinese[recoveryHint.trim()]}`;
  }
  return interpolate(message, values);
}

export function localizedDate(value: number | null | undefined, locale: Locale, precision: DatePrecision = "instant"): string {
  if (value == null || !Number.isFinite(value)) return "—";
  const instant = new Date(value * 1000);
  if (Number.isNaN(instant.getTime())) return "—";
  const language = locale === "zh-CN" ? "zh-CN" : "en-US";
  return precision === "day" ? instant.toLocaleDateString(language, { timeZone: "UTC" }) : instant.toLocaleString(language);
}
